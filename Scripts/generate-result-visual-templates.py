#!/usr/bin/env python3
"""Generate fixed visual marker samples; OpenCV is a development-only dependency.

No OCR, resizing of source files, or game interaction. The generated Swift samples use
the same integer luminance and bilinear sampling as VisualResultDetector.
"""
from pathlib import Path
import base64
import hashlib
import json
import sys
import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mirror_content_layout import canvas  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
REGIONS = {
    "successTitle": (.38, .10, .24, .034),
    "failureTitle": (.38, .10, .24, .034),
    "experienceHeader": (.775, .145, .20, .026),
    "lootHeader": (.775, .145, .20, .026),
    "repeatOption": (.022, .234, .29, .025),
}
# Sources sampled before the zoom-level canvas existed stay raw so their bytes never change;
# the runtime canvas differs from a raw 2x capture by at most one pixel, inside the
# registration search. Zoom-level captures (the smaller window sizes from 顯示方式 > 縮小)
# must be placed on the reference canvas first, exactly as the runtime does.
RAW = "raw"
ZOOM = "zoom"
ZOOM_LOOT = ["Tests/MirrorProbeCoreTests/Fixtures/zoom-loot-result-211x468.png",
             "Tests/MirrorProbeCoreTests/Fixtures/zoom-loot-result-250x553.png",
             "Tests/MirrorProbeCoreTests/Fixtures/zoom-loot-result-289x637.png",
             "Tests/MirrorProbeCoreTests/Fixtures/zoom-loot-result-328x722.png"]
SOURCES = {
    "successTitle": [(RAW, "Tests/MirrorProbeCoreTests/Fixtures/Images/mission-repeat-selected-srlected.png"),
                     (RAW, "Tests/MirrorProbeCoreTests/Fixtures/low-result-title-experience.png")]
                    + [(ZOOM, path) for path in ZOOM_LOOT],
    "failureTitle": [(RAW, "Tests/MirrorProbeCoreTests/Fixtures/failure-repeat-confirmation-before.png")],
    "experienceHeader": [(RAW, "Tests/MirrorProbeCoreTests/Fixtures/Images/mission-repeat-selected-srlected.png"),
                         (RAW, "Tests/MirrorProbeCoreTests/Fixtures/low-result-title-experience.png")],
    "lootHeader": [(RAW, "Tests/MirrorProbeCoreTests/Fixtures/Images/mission-result-no-modal.png"),
                   (RAW, "Tests/MirrorProbeCoreTests/Fixtures/low-result-title-startup.png")]
                  + [(ZOOM, path) for path in ZOOM_LOOT],
    "repeatOption": [(RAW, "Tests/MirrorProbeCoreTests/Fixtures/Images/mission-repeat-selected-srlected.png"),
                     (RAW, "Tests/MirrorProbeCoreTests/Fixtures/low-result-title-experience.png")]
                    + [(ZOOM, path) for path in ZOOM_LOOT],
}

def samples(path, region, placement=RAW):
    bgr = cv2.imread(str(path), cv2.IMREAD_COLOR)
    if placement == ZOOM:
        bgr = canvas(bgr)
    bgr = bgr.astype(np.int32)
    gray = ((77*bgr[:, :, 2] + 150*bgr[:, :, 1] + 29*bgr[:, :, 0]) >> 8).astype(float)
    height, width = gray.shape
    x, y, w, h = region
    xx, yy = np.meshgrid((x+(np.arange(96)+.5)*w/96)*width-.5,
                         (y+(np.arange(24)+.5)*h/24)*height-.5)
    x0, y0 = np.floor(xx).astype(int), np.floor(yy).astype(int)
    tx, ty = xx-x0, yy-y0
    values = ((1-ty)*((1-tx)*gray[y0, x0]+tx*gray[y0, x0+1])
              + ty*((1-tx)*gray[y0+1, x0]+tx*gray[y0+1, x0+1]))
    return np.floor(values+.5).astype(np.uint8).tobytes()

lines = ["// Generated by scripts/generate-result-visual-templates.py; do not edit sample bytes.",
         "import Foundation", "", "enum VisualResultTemplates {",
         "    static let sampleWidth = 96", "    static let sampleHeight = 24",
         "    static let samples: [VisualResultMarker: [[UInt8]]] = ["]
manifest = []
for marker, sources in SOURCES.items():
    lines.append(f"        .{marker}: [")
    for placement, path in sources:
        raw = samples(ROOT/path, REGIONS[marker], placement)
        encoded = base64.b64encode(raw).decode()
        note = " (placed on the reference canvas)" if placement == ZOOM else ""
        lines.append(f"            // {path}{note}")
        lines.append(f'            Array(Data(base64Encoded: "{encoded}")!),')
        manifest.append({"marker": marker, "region": REGIONS[marker], "source": path,
                         "placement": placement,
                         "sourceSHA256": hashlib.sha256((ROOT/path).read_bytes()).hexdigest(),
                         "sampleSHA256": hashlib.sha256(raw).hexdigest()})
    lines.append("        ],")
lines += ["    ]", "}", ""]
(ROOT/"Sources/MirrorProbeCore/VisualResultTemplates.swift").write_text("\n".join(lines))
destination = ROOT/"DevelopmentFixtures/ClassifierReplaySources/result-visual-20260911"
destination.mkdir(parents=True, exist_ok=True)
(destination/"templates.json").write_text(json.dumps(manifest, indent=2)+"\n")
